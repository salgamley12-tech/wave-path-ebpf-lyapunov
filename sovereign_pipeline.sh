#!/bin/bash

# إيقاف التنفيذ فوراً في حال حدوث أي خطأ برمجي
set -e

echo "=================================================="
echo "🚀 [AQI Sovereign Kernel] بدء تشغيل مسار العمل الشامل..."
echo "=================================================="

# المرحلة الأولى: تنظيف وبناء المشروع
echo "[1/5] جاري فحص وبناء الكود عبر Cargo..."
cargo build --release

# المرحلة الثانية: تشغيل اختبارات الوحدة والتحقق
echo "[2/5] جاري تشغيل اختبارات الوحدة (Unit Tests)..."
cargo test

# المرحلة الثالثة: تتبع التعديلات البرمجية عبر Git
echo "[3/5] جاري تحديث وتتبع المستودع المحلي..."
git add .

# التحقق مما إذا كانت هناك تغييرات تتطلب التزاماً
if git diff-index --quiet HEAD --; then
    echo "ℹ️ لا توجد تغييرات جديدة تستوجب الالتزام (No changes to commit)."
else
    echo "[4/5] جاري توثيق الالتزام السيادي..."
    git commit -m "Sovereign Kernel Update: Tri-Core Integration & Pipeline Sync $(date +'%Y-%m-%d %H:%M:%S')"
fi

# المرحلة الخامسة: المزامنة والدفع إلى المستودع البعيد على GitHub
echo "[5/5] جاري مزامنة ورفع التحديثات إلى GitHub..."
git push origin main

echo "=================================================="
echo "✨ تم إنجاز مسار العمل السيادي بنجاح تام وتم تحديث النظام!"
echo "=================================================="
